/* Ручной («досыпанный») доход за декабрь 2025.
 *
 * В источнике чистой прибыли (P&L-API финансовой платформы) декабря нет — компания
 * перешла на платформу позже, и за этот месяц данные не отдаются. Значения заданы
 * заказчиком по неделям (Пн–Вс, как колонки «Отчёта»); недельный ключ — weekEnd
 * (воскресенье) в формате "YYYY-MM-DD", совпадает с ключами недель расходов.
 *
 * Мерджится в гистограмму «расходы/доходы» на этапе ЧТЕНИЯ (src/lib/data.ts), а не в
 * БД: синк доходов делает полную перезапись (deleteMany), поэтому запись в БД была бы
 * затёрта. Чтение-слой всегда показывает эти значения и не зависит от нестабильного
 * P&L-API. Это разовый исторический backfill; при появлении декабря в источнике
 * строку можно удалить. */

export interface SupplementalIncome {
  key: string; // weekEnd "YYYY-MM-DD" (недели) или период "YYYY-MM" (месяцы)
  usd: number;
  label: string; // для наглядности/диагностики
}

